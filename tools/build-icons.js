'use strict';

// Writes www/icons.js: the icons of the firmware (lib/layout.js ICONS) as SVG paths of Material Design Icons 7.4.47
// (Pictogrammers, Apache License 2.0), the version whose font the firmware uses and the admin editor imports
// (src-admin/src/icons.tsx). Run it after the list changes: node tools/build-icons.js

const fs = require('node:fs');
const path = require('node:path');
const { ICONS } = require('../lib/layout');

const mdi = require(path.join(__dirname, '..', 'src-admin', 'node_modules', '@mdi', 'js'));

/**
 * @param {string} name - e.g. ceiling-light
 * @returns {string} e.g. mdiCeilingLight
 */
const exportOf = name => `mdi${name.replace(/(^|-)([a-z])/g, (_m, _d, c) => c.toUpperCase())}`;

const paths = {};
for (const name of ICONS) {
    const p = mdi[exportOf(name)];
    if (!p) {
        throw new Error(`@mdi/js has no ${exportOf(name)}`);
    }
    paths[name] = p;
}

const out = `// Generated by tools/build-icons.js - do not edit.
// Material Design Icons 7.4.47 (https://pictogrammers.com), Apache License 2.0: the icons of the satellite firmware.
self.TILE_ICONS = ${JSON.stringify(paths, null, 4)};
`;
fs.writeFileSync(path.join(__dirname, '..', 'www', 'icons.js'), out);
console.log(`www/icons.js: ${ICONS.length} icons`);
